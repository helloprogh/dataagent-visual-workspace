function readLocale(): SupportedLocale {
  const stored = typeof window !== 'undefined' ? window.localStorage.getItem(localeStorageKey) : null
  if (stored && supportedLocales.includes(stored as SupportedLocale)) return stored as SupportedLocale
  if (typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('en')) return 'en-US'
  return 'zh-CN'
}

export const i18n = createI18n({
  legacy: false,
  locale: readLocale(),
  fallbackLocale: 'zh-CN',
  messages,
})

export function setLocale(locale: SupportedLocale) {
  i18n.global.locale.value = locale
  if (typeof window !== 'undefined') window.localStorage.setItem(localeStorageKey, locale)
  if (typeof document !== 'undefined') document.documentElement.lang = locale
}

export function toggleLocale() {
  setLocale(i18n.global.locale.value === 'zh-CN' ? 'en-US' : 'zh-CN')
}

setLocale(i18n.global.locale.value as SupportedLocale)
